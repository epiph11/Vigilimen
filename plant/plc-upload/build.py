"""Build the files that are uploaded to OpenPLC.

OpenPLC's compiler needs a CONFIGURATION block (resource, task, program
instance); the sources in plc-control/ and plc-safety/ are deliberately just
the PROGRAM. Keeping the wiring here means FF-21 keeps checking the program
exactly as it is on disk, and nothing is hand-edited twice.

    python plant/plc-upload/build.py

Writes plc-upload/conveyor_upload.st and plc-upload/safety_upload.st.
Upload THOSE to OpenPLC, not the sources. Do not edit them by hand.
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
PLANT = HERE.parent

TARGETS = [
    (PLANT / "plc-control" / "conveyor.st", "PLC_CONV_001", "conveyor_upload.st"),
    (PLANT / "plc-safety" / "safety.st", "SIS_CONV_001", "safety_upload.st"),
]

WIRING = """

(* ---------------------------------------------------------------------
   GENERATED by plant/plc-upload/build.py. Source: {src}
   Only this block is added. Edit the source, then rebuild.
   --------------------------------------------------------------------- *)
CONFIGURATION Config0
  RESOURCE Res0 ON PLC
    TASK task0(INTERVAL := T#20ms, PRIORITY := 0);
    PROGRAM instance0 WITH task0 : {prog};
  END_RESOURCE
END_CONFIGURATION
"""

for src, prog, out in TARGETS:
    text = src.read_text(encoding="utf-8").replace("\r\n", "\n").rstrip() + "\n"
    (HERE / out).write_text(text + WIRING.format(src=src.name, prog=prog),
                            encoding="utf-8", newline="\n")
    print(f"wrote plc-upload/{out}")
